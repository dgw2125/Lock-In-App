import Foundation

@MainActor func runTests() throws {
    var checks = 0
    func expect(_ condition: @autoclosure () -> Bool, _ message: String) {
        checks += 1
        if !condition() { fatalError(message) }
    }
    expect(DomainRule.normalize(" HTTPS://Instagram.com/person ") == "instagram.com", "URL normalization")
    expect(DomainRule.normalize("bad host.com") == nil, "Reject spaces")
    expect(DomainRule.normalize("https://user@instagram.com") == nil, "Reject credentials")
    expect(DomainRule.normalize("-bad.com") == nil, "Reject malformed label")
    expect(DomainRule.matches("https://a.b.instagram.com/person", domains: ["instagram.com"]), "Subdomains")
    expect(DomainRule.matches("https://instagram.com:443/person", domains: ["instagram.com"]), "Ports")
    expect(!DomainRule.matches("https://notinstagram.com", domains: ["instagram.com"]), "Domain boundary")
    expect(!DomainRule.matches("https://instagram.com.evil.org", domains: ["instagram.com"]), "Suffix spoof")
    expect(!DomainRule.matches("https://example.com/instagram.com", domains: ["instagram.com"]), "Path spoof")
    expect(!DomainRule.matches("https://instagram.com@evil.org", domains: ["instagram.com"]), "Userinfo spoof")
    let dir = FileManager.default.temporaryDirectory.appendingPathComponent("lockin-test-" + UUID().uuidString)
    defer { try? FileManager.default.removeItem(at: dir) }
    let model = AppModel(directory: dir, ticking: false, browserMonitoring: false)
    expect(model.add("instagram.com"), "Add domain")
    model.start(seconds: 0)
    expect(model.active == nil, "Reject zero duration")
    model.start(seconds: FocusDuration.maximum + 1)
    expect(model.active == nil, "Reject over six hours at model boundary")
    expect(FocusDuration.isValid(1), "Allow a one-second session")
    expect(FocusDuration.isValid(21600), "Allow exactly six hours")
    expect(!FocusDuration.isValid(-1), "Reject negative duration")
    expect(FocusDuration.seconds(hours: 6, minutes: 15, seconds: 30) == 21600, "Clamp picker at six hours")
    expect(FocusDuration.seconds(hours: 1, minutes: 2, seconds: 3) == 3723, "Combine hour minute second values")
    expect(FocusDuration.countdown(3723) == "1:02:03", "Hour countdown")
    expect(FocusDuration.countdown(25) == "00:25", "Sub-minute countdown")
    // Persist an active session directly to avoid triggering real browser automation in tests.
    let start = Date().addingTimeInterval(-30)
    model.state.active = FocusSession(start: start, scheduledEnd: start.addingTimeInterval(1500), lastSeen: Date(), initialDomains: model.state.domains)
    model.remove("instagram.com")
    expect(model.state.domains == ["instagram.com"], "No active removal")
    model.state.active?.additions.append(Addition(domain: "reddit.com", date: Date()))
    expect(model.active?.domains == ["instagram.com", "reddit.com"], "Session additions")
    expect(model.save(), "Persist")
    let restored = AppModel(directory: dir, ticking: false, browserMonitoring: false)
    expect(restored.active == nil, "No silent resumption")
    expect(restored.state.history.count == 1, "Recover history")
    expect(restored.state.history[0].outcome == "interrupted", "Interrupted outcome")
    expect(restored.state.history[0].actualSeconds >= 29, "Elapsed recovery")
    expect(restored.state.history[0].additions.count == 1, "Persist additions")
    model.finish("ended early")
    model.remove("instagram.com")
    expect(model.state.domains.isEmpty, "Allow removal after ending")
    expect(model.state.history[0].initialDomains == ["instagram.com"], "History snapshot immutable")
    var expired = FocusSession(start: start, scheduledEnd: start.addingTimeInterval(10), lastSeen: start, initialDomains: [])
    expired.finish(at: Date(), outcome: "completed")
    expect(expired.actualSeconds == 10, "Cap completion at scheduled end")
    let csv = exportCSV(restored.state.history)
    expect(csv.contains("interrupted") && csv.contains("reddit.com @"), "CSV history and additions")
    expect(csvField("=SUM(1)") == "\"'=SUM(1)\"", "CSV formula protection")
    // Advance time deterministically: no real waiting and no browser automation.
    var testNow = Date(timeIntervalSince1970: 1_800_000_000)
    let countdownDirectory = dir.appendingPathComponent("countdown")
    let delayed = AppModel(directory: countdownDirectory, ticking: false, browserMonitoring: false, clock: { testNow })
    delayed.schedule(seconds: 1500, after: 60)
    expect(delayed.scheduled == nil, "Cannot schedule an empty block list")
    expect(delayed.add("instagram.com"), "Prepare delayed session")
    delayed.schedule(seconds: 0, after: 60)
    expect(delayed.scheduled == nil, "Reject invalid scheduled focus duration")
    delayed.schedule(seconds: 1500, after: -1)
    expect(delayed.scheduled == nil, "Reject negative delay")
    delayed.schedule(seconds: 1500, after: ScheduledFocus.maximumDelay + 1)
    expect(delayed.scheduled == nil, "Reject delay beyond picker range")
    delayed.schedule(seconds: 1500, after: 60)
    expect(delayed.scheduled != nil && delayed.active == nil, "Countdown does not activate blocking")
    expect(delayed.delayRemaining == 60 && delayed.menuTitle == "Starts in 01:00", "Menu bar identifies pre-session time")
    let firstDeadline = delayed.scheduled!.startsAt
    delayed.schedule(seconds: 300, after: 1)
    delayed.start(seconds: 300)
    expect(delayed.scheduled?.startsAt == firstDeadline && delayed.active == nil, "Prevent overlapping starts")
    testNow = testNow.addingTimeInterval(59)
    delayed.tick()
    expect(delayed.active == nil && delayed.delayRemaining == 1, "No premature session start")
    expect(delayed.add("reddit.com"), "Allow edits during countdown")
    delayed.remove("instagram.com")
    testNow = testNow.addingTimeInterval(1)
    delayed.tick()
    expect(delayed.scheduled == nil && delayed.active != nil, "Start automatically at deadline")
    expect(delayed.active?.start == testNow && delayed.remaining == 1500, "Countdown does not consume focus time")
    expect(delayed.active?.initialDomains == ["reddit.com"], "Use current list when blocking starts")
    delayed.cancelScheduled()
    expect(delayed.active != nil, "Countdown cancellation cannot bypass an active block")
    delayed.schedule(seconds: 300, after: 1)
    expect(delayed.scheduled == nil, "No scheduling while active")
    delayed.tick()
    expect(delayed.state.history.isEmpty, "Do not record countdown as completed focus time")
    testNow = testNow.addingTimeInterval(1500)
    delayed.tick()
    expect(delayed.state.history.count == 1 && delayed.state.history[0].actualSeconds == 1500, "Record only actual focus session")
    delayed.schedule(seconds: 120, after: 30)
    delayed.cancelScheduled()
    testNow = testNow.addingTimeInterval(31)
    delayed.tick()
    expect(delayed.active == nil && delayed.state.history.count == 1, "Cancelled countdown never starts or adds history")
    delayed.schedule(seconds: 120, after: 30)
    testNow = testNow.addingTimeInterval(600)
    delayed.tick()
    expect(delayed.remaining == 120 && delayed.active?.start == testNow, "Late wake starts a full session at actual wake time")
    delayed.finish("ended early")
    delayed.schedule(seconds: 60, after: 30)
    let relaunched = AppModel(directory: countdownDirectory, ticking: false, browserMonitoring: false, clock: { testNow })
    expect(relaunched.scheduled == nil && relaunched.active == nil, "No surprise scheduled blocking after relaunch")
    delayed.remove("reddit.com")
    expect(delayed.scheduled == nil && delayed.state.domains.isEmpty, "Removing final domain cancels countdown")
    expect(delayed.add("example.com"), "Prepare immediate start")
    delayed.schedule(seconds: 1, after: 0)
    expect(delayed.active != nil && delayed.remaining == 1, "Zero delay retains immediate-start behavior")
    testNow = testNow.addingTimeInterval(1)
    delayed.tick()
    expect(delayed.active == nil && delayed.state.history[0].outcome == "completed", "One-second immediate session completes")
    print("All \(checks) duration, countdown, session, persistence and CSV checks passed.")
}
try MainActor.assumeIsolated { try runTests() }
